"""
Extra: build a usage-enriched data catalog that helps AI agents (and people)
discover, understand and choose tables.

For every Iceberg table it combines catalog metadata (owner, description)
with usage facts (popularity, users, teams, tables it is usually joined with).

Writes:
  docs/data_catalog.json   -> machine-readable, for AI agents
  docs/data_catalog.md     -> human-readable

Usage:
  python pipeline/build_data_catalog.py
"""
import json
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = ROOT / "data" / "meta_dwh.duckdb"
DOCS_DIR = ROOT / "docs"

CATALOG_SQL = """
WITH usage AS (
    SELECT
        table_id,
        COUNT(*)                   AS queries_30d,
        COUNT(DISTINCT user_name)  AS distinct_users_30d,
        LIST(DISTINCT team_id ORDER BY team_id) AS used_by_teams,
        MAX(query_date)            AS last_queried_date
    FROM core.fact_query_table_access
    -- last 30 days, counted back from the newest data
    WHERE query_date > (SELECT MAX(query_date) FROM core.fact_query_table_access) - INTERVAL 30 DAY
    GROUP BY table_id
),
co_access AS (
    -- tables read in the same query = tables that are usually joined together
    SELECT a.table_id, b.table_id AS other_table, COUNT(*) AS times
    FROM core.fact_query_table_access a
    JOIN core.fact_query_table_access b
      ON a.query_id = b.query_id AND a.table_id <> b.table_id
    GROUP BY a.table_id, b.table_id
    QUALIFY ROW_NUMBER() OVER (PARTITION BY a.table_id ORDER BY COUNT(*) DESC, other_table) <= 3
),
co_list AS (
    SELECT table_id, LIST(other_table ORDER BY times DESC, other_table) AS often_queried_with
    FROM co_access
    GROUP BY table_id
)
SELECT
    t.table_id,
    t.description,
    t.owner_team_id,
    COALESCE(u.queries_30d, 0)        AS queries_30d,
    COALESCE(u.distinct_users_30d, 0) AS distinct_users_30d,
    COALESCE(u.used_by_teams, [])     AS used_by_teams,
    CAST(u.last_queried_date AS VARCHAR) AS last_queried_date,
    COALESCE(c.often_queried_with, []) AS often_queried_with,
    CASE WHEN COALESCE(u.queries_30d, 0) = 0 THEN 'cold' ELSE 'active' END AS status,
    RANK() OVER (ORDER BY COALESCE(u.queries_30d, 0) DESC) AS popularity_rank
FROM core.dim_table t
LEFT JOIN usage u   ON u.table_id = t.table_id
LEFT JOIN co_list c ON c.table_id = t.table_id
ORDER BY popularity_rank, t.table_id
"""


def main():
    con = duckdb.connect(str(DB_PATH), read_only=True)
    cursor = con.execute(CATALOG_SQL)
    columns = [d[0] for d in cursor.description]
    tables = [dict(zip(columns, row)) for row in cursor.fetchall()]
    con.close()

    with open(DOCS_DIR / "data_catalog.json", "w", encoding="utf-8") as f:
        json.dump({"tables": tables}, f, indent=2)

    lines = ["# Data Catalog", "",
             "Generated by `pipeline/build_data_catalog.py` from catalog metadata and usage data.", ""]
    for t in tables:
        lines += [
            f"## {t['table_id']}",
            f"- **Description:** {t['description']}",
            f"- **Owner:** {t['owner_team_id']}  |  **Status:** {t['status']}"
            f"  |  **Popularity rank:** {t['popularity_rank']}",
            f"- **Usage (30 days):** {t['queries_30d']} queries, "
            f"{t['distinct_users_30d']} distinct users, last queried {t['last_queried_date'] or 'never'}",
            f"- **Used by teams:** {', '.join(t['used_by_teams']) or '-'}",
            f"- **Often queried with:** {', '.join(t['often_queried_with']) or '-'}",
            "",
        ]
    (DOCS_DIR / "data_catalog.md").write_text("\n".join(lines), encoding="utf-8")

    print(f"Catalog built for {len(tables)} tables:")
    print(f"  {DOCS_DIR / 'data_catalog.json'}")
    print(f"  {DOCS_DIR / 'data_catalog.md'}")


if __name__ == "__main__":
    main()